// Builds server/sql/schema.pg.sql from the current SQLite schema (run once; output is committed).
const Database = require('better-sqlite3');
const fs = require('fs');
const path = require('path');
const src = new Database(process.argv[2] || path.join(__dirname, '..', 'data', 'achzaka.db'), { readonly: true });
const tables = src.prepare(`SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY rowid`).all().map((r) => r.name);
const pgType = (t) => {
  t = (t || '').toUpperCase();
  if (t.includes('INT')) return 'BIGINT';
  if (t.includes('REAL') || t.includes('FLOA') || t.includes('DOUB')) return 'DOUBLE PRECISION';
  return 'TEXT';
};
// order tables so referenced tables come first
const fks = Object.fromEntries(tables.map((t) => [t, src.prepare(`PRAGMA foreign_key_list(${t})`).all()]));
const ordered = [];
const visit = (t, seen = new Set()) => {
  if (ordered.includes(t) || seen.has(t)) return;
  seen.add(t);
  for (const fk of fks[t]) if (fk.table !== t && tables.includes(fk.table)) visit(fk.table, seen);
  ordered.push(t);
};
tables.forEach((t) => visit(t));
let out = '-- PostgreSQL schema for אחזקה. Generated from the SQLite schema by scripts/gen-pg-schema.js.\n-- Idempotent: safe to run on every start.\n\n';
for (const t of ordered) {
  const cols = src.prepare(`PRAGMA table_info(${t})`).all();
  const lines = cols.map((c) => {
    if (c.pk === 1 && cols.filter((x) => x.pk).length === 1 && /^INTEGER$/i.test(c.type)) {
      return `  ${c.name} BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY`;
    }
    let l = `  ${c.name} ${pgType(c.type)}`;
    if (c.pk) l += ' PRIMARY KEY';
    if (c.notnull) l += ' NOT NULL';
    if (c.dflt_value != null) l += ` DEFAULT ${c.dflt_value}`;
    return l;
  });
  const uniq = src.prepare(`PRAGMA index_list(${t})`).all().filter((i) => i.origin === 'u');
  for (const u of uniq) lines.push(`  UNIQUE (${src.prepare(`PRAGMA index_info(${u.name})`).all().map((c) => c.name).join(', ')})`);
  for (const fk of fks[t]) lines.push(`  FOREIGN KEY (${fk.from}) REFERENCES ${fk.table}(${fk.to})`);
  out += `CREATE TABLE IF NOT EXISTS ${t} (\n${lines.join(',\n')}\n);\n\n`;
}
for (const r of src.prepare(`SELECT sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL ORDER BY rowid`).all()) {
  out += `${r.sql.replace(/^CREATE (UNIQUE )?INDEX (IF NOT EXISTS )?/i, (m, u) => `CREATE ${u || ''}INDEX IF NOT EXISTS `)};\n`;
}
// hot paths for a busy client
out += `CREATE INDEX IF NOT EXISTS idx_calls_status ON calls(status);\nCREATE INDEX IF NOT EXISTS idx_calls_created ON calls(created_at);\nCREATE INDEX IF NOT EXISTS idx_calls_vendor ON calls(vendor_id);\nCREATE INDEX IF NOT EXISTS idx_sessions_expires ON sessions(expires_at);\nCREATE INDEX IF NOT EXISTS idx_emails_building ON outbound_emails(building_id);\n`;
fs.writeFileSync(path.join(__dirname, '..', 'server', 'sql', 'schema.pg.sql'), out);
console.log('tables', ordered.length);
